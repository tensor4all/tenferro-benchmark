#!/usr/bin/env python3
"""Write the CPU-pinning rows of the declared profiles to a TSV table.

`benchmarks/profiles.yaml` names the hardware profiles this repository measures.
A profile's identity -- its CPU label, SMT layout, power policy and thread rows --
is a fact about a machine, so it lives in campaign_toolkit's shared profile
library. This script copies the library's thread rows into
``benchmarks/cpu_pinning_rows.tsv``, which ``scripts/cpu_pinning.sh`` reads with
bash/awk only: pinning a row must not need an interpreter or the toolkit.

The table has one row per ``(profile, threads)``::

    profile<TAB>threads<TAB>measured_cpus<TAB>observer_cpus

A profile with no row for a thread count is an error at pin time; a profile that
is absent from the table is unpinned, which is how the legacy profiles behave.

Run ``python3 scripts/sync_pinning_rows.py`` after editing ``profiles.yaml`` or
moving the toolkit revision; ``--check`` fails when the checked-in table is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from campaign_toolkit.descriptor import DescriptorError, shared_profile

ROOT = Path(__file__).resolve().parents[1]
PROFILES = ROOT / "benchmarks/profiles.yaml"
ROWS = ROOT / "benchmarks/cpu_pinning_rows.tsv"

HEADER = (
    "# Generated by scripts/sync_pinning_rows.py from campaign_toolkit's shared\n"
    "# profile library; do not edit.\n"
    "profile\tthreads\tmeasured_cpus\tobserver_cpus\n"
)


def declared_profiles():
    """The profile names in `benchmarks/profiles.yaml`, maintained first."""
    document = yaml.safe_load(PROFILES.read_text())
    if not isinstance(document, dict):
        raise SystemExit(f"ERROR: {PROFILES.relative_to(ROOT)} does not hold a mapping")
    names = []
    for key in ("maintained", "optional"):
        for name in document.get(key) or []:
            name = str(name)
            if name not in names:
                names.append(name)
    return names


def render() -> str:
    lines = [HEADER]
    for name in declared_profiles():
        try:
            profile = shared_profile(name)
        except DescriptorError as error:
            raise SystemExit(f"ERROR: {PROFILES.relative_to(ROOT)}: {error}")
        rows = profile.get("thread_rows") or []
        if rows and profile.get("name") and profile["name"] != name:
            raise SystemExit(
                f"ERROR: shared profile {name!r} declares name {profile['name']!r}"
            )
        for row in rows:
            threads = row.get("threads")
            if not isinstance(threads, int) or threads < 1:
                raise SystemExit(f"ERROR: {name}: invalid thread row {row!r}")
            lines.append(
                f"{name}\t{threads}\t{row.get('measured', '')}\t{row.get('observer', '')}\n"
            )
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the checked-in table is stale"
    )
    args = parser.parse_args()
    text = render()
    if args.check:
        if not ROWS.exists() or ROWS.read_text() != text:
            print(f"stale: {ROWS.relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    ROWS.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
