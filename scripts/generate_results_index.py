#!/usr/bin/env python3
"""Generate a static HTML index for benchmark reports.

The script scans Markdown reports under a result tree and emits index.html.
It also copies each report into the output tree so the site is self-contained.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

import markdown


def discover_reports(result_dir: Path) -> list[tuple[str, str, Path]]:
    """Return (target_profile, suite_id, relative_path) for every report."""
    reports: list[tuple[str, str, Path]] = []
    if not result_dir.exists():
        return reports
    for profile_dir in sorted(result_dir.iterdir()):
        if not profile_dir.is_dir():
            continue
        profile = profile_dir.name
        for suite_dir in sorted(profile_dir.iterdir()):
            if not suite_dir.is_dir():
                continue
            for report in sorted(suite_dir.glob("*.md")):
                suite_id = f"{suite_dir.name}/{report.stem}"
                reports.append((profile, suite_id, report))
    return reports


def build_index(reports: list[tuple[str, str, Path]]) -> str:
    sections: dict[str, list[tuple[str, str]]] = {}
    for profile, suite_id, path in reports:
        sections.setdefault(profile, []).append((suite_id, path.name))

    lines = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '  <meta charset="UTF-8">',
        '  <meta name="viewport" content="width=device-width, initial-scale=1.0">',
        "  <title>tenferro-benchmark results</title>",
        "  <style>",
        "    body { font-family: system-ui, -apple-system, sans-serif; max-width: 960px; margin: 2rem auto; padding: 0 1rem; color: #222; }",
        "    h1 { border-bottom: 2px solid #333; padding-bottom: .3rem; }",
        "    h2 { margin-top: 2rem; color: #444; }",
        "    ul { line-height: 1.8; }",
        "    a { color: #0366d6; text-decoration: none; }",
        "    a:hover { text-decoration: underline; }",
        "    .notice { background: #fff8c5; border-left: 4px solid #f9c513; padding: .75rem 1rem; margin: 1rem 0; }",
        "    footer { margin-top: 3rem; font-size: .85rem; color: #666; border-top: 1px solid #ddd; padding-top: 1rem; }",
        "  </style>",
        "</head>",
        "<body>",
        "  <h1>tenferro-benchmark results</h1>",
        '  <p class="notice">',
        "    <strong>Reference-quality indicators only.</strong> "
        "    GitHub-hosted runners are shared infrastructure with variable load, "
        "    so these numbers are useful for spot-checks but not for strict "
        "    regression tracking. Canonical regression series require stable "
        "    dedicated runners.",
        "  </p>",
        '  <p>Latest benchmark reports by target profile and suite.</p>',
    ]

    if not sections:
        lines.append("  <p>No reports found.</p>")
    else:
        for profile in sorted(sections):
            lines.append(f"  <h2>{profile}</h2>")
            lines.append("  <ul>")
            for suite_id, filename in sorted(sections[profile]):
                href = f"{profile}/{suite_id.split('/')[0]}/{filename}"
                display = suite_id
                lines.append(f'    <li><a href="{href}">{display}</a></li>')
            lines.append("  </ul>")

    lines.extend([
        "  <footer>",
        '    Generated by <code>scripts/generate_results_index.py</code> from the <a href="https://github.com/tensor4all/tenferro-benchmark">tensor4all/tenferro-benchmark</a> repository.',
        "  </footer>",
        "</body>",
        "</html>",
    ])
    return "\n".join(lines) + "\n"


def render_markdown(report: Path, output_dir: Path) -> Path:
    """Render a Markdown report to HTML and copy the source Markdown."""
    html = markdown.markdown(
        report.read_text(encoding="utf-8"),
        extensions=["tables", "fenced_code"],
    )
    out_html = output_dir / f"{report.stem}.html"
    out_html.write_text(
        f"<!DOCTYPE html>\n"
        '<html lang="en">\n<head>\n'
        '  <meta charset="UTF-8">\n'
        '  <meta name="viewport" content="width=device-width, initial-scale=1.0">\n'
        f"  <title>{report.stem}</title>\n"
        "  <style>\n"
        "    body { font-family: system-ui, -apple-system, sans-serif; max-width: 960px; margin: 2rem auto; padding: 0 1rem; color: #222; }\n"
        "    table { border-collapse: collapse; margin: 1rem 0; }\n"
        "    th, td { border: 1px solid #ddd; padding: .4rem .6rem; text-align: left; }\n"
        "    th { background: #f6f8fa; }\n"
        "    code { background: #f6f8fa; padding: .1rem .3rem; border-radius: 3px; }\n"
        "    pre { background: #f6f8fa; padding: 1rem; overflow-x: auto; }\n"
        "  </style>\n"
        "</head>\n<body>\n"
        f'{html}\n'
        '</body>\n</html>\n',
        encoding="utf-8",
    )
    shutil.copy2(report, output_dir / report.name)
    return out_html


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--result-dir", type=Path, default=Path("result"))
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    reports = discover_reports(args.result_dir)
    if not reports:
        print(f"warning: no reports found under {args.result_dir}", file=sys.stderr)

    for profile, suite_id, report in reports:
        suite_dir = output_dir / profile / suite_id.split("/")[0]
        suite_dir.mkdir(parents=True, exist_ok=True)
        render_markdown(report, suite_dir)

    index_html = build_index(reports)
    (output_dir / "index.html").write_text(index_html, encoding="utf-8")

    print(f"generated site in {output_dir} with {len(reports)} reports")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
