"""Generate a CPU-only official Actions transfer trial; no RunPod secrets."""
import json
from pathlib import Path
import yaml

ROOT=Path(__file__).resolve().parents[2]
P=ROOT/'result/linux-cpu/ci/artifact-transfer-protocol.json'
protocol=json.loads(P.read_text())
UPLOAD='actions/upload-artifact@043fb46d1a93c77aae656e7c1c64a875d1fc6a0a'
DOWNLOAD='actions/download-artifact@3e5f45b2cfb9172054b4087a40e8e0b5a5461e7c'
CHECKOUT='actions/checkout@9c091bb21b7c1c1d1991bb908d89e4e9dddfe3e0'
checkout={'uses':CHECKOUT,'with':{'persist-credentials':False}}
prepare=[checkout,{'name':'Verify frozen source artifacts','env':{'GH_TOKEN':'${{ github.token }}'},'run':'''gh api repos/tensor4all/tenferro-rs/actions/runs/38056837195/artifacts > source-artifacts.json
python3 - <<'PYCODE'
import json
p=json.load(open('result/linux-cpu/ci/artifact-transfer-protocol.json'))
a=json.load(open('source-artifacts.json'))['artifacts']
for row in p['source_artifacts']:
 found=[x for x in a if x['id']==row['id']]
 assert len(found)==1 and not found[0]['expired']
 assert all(found[0][k]==v for k,v in row.items())
PYCODE'''}]
for case in ['common','cuda12.8']:
 prepare.append({'name':f'Download source {case}','uses':DOWNLOAD,'timeout-minutes':5,'with':{
  'repository':'tensor4all/tenferro-rs','run-id':38056837195,'github-token':'${{ github.token }}',
  'pattern':f'gpu-runtime-38056837195-{case}-part*','merge-multiple':True,'path':f'source/{case}'}})
prepare.append({'name':'Prepare identical byte streams','run':'python3 scripts/artifact-transfer/experiment.py prepare'})
for case in ['common','cuda12.8']:
 for i in range(5):
  # Interleave publication order; raw filename is necessarily its artifact name.
  for arm in ['zip','raw']:
   settings={'path':f'upload/{arm}/{case}/{i:02}/' if arm=='zip' else f'upload/raw/raw-{case}-part{i:02}',
             'if-no-files-found':'error','retention-days':1}
   if arm=='zip': settings.update(name=f'zip-{case}-part{i:02}', **{'compression-level':0})
   else: settings['archive']=False
   prepare.append({'name':f'Upload {arm} {case} {i:02}','uses':UPLOAD,'with':settings,'timeout-minutes':5})
prepare.append({'uses':UPLOAD,'with':{'name':'transfer-manifest','path':'manifest.json','retention-days':7}})
measure=[{**checkout, "with": dict(checkout["with"])},{'name':'Record host','run':'''mkdir -p evidence
lscpu > evidence/lscpu.txt
uname -a > evidence/uname.txt
cat /etc/os-release > evidence/os-release.txt
cat /proc/meminfo > evidence/meminfo.txt
printf '%s\\n' "${ImageOS:-unknown}" "${ImageVersion:-unknown}" > evidence/runner-image.txt
git rev-parse HEAD > evidence/harness-commit.txt'''},
 {'name':'Read expected file hashes','uses':DOWNLOAD,'with':{'name':'transfer-manifest'}}]
for index,arm in enumerate(protocol['order']):
 for case in ['common','cuda12.8']:
  measure.append({'name':f'Begin {index} {arm} {case}','run':f'python3 scripts/artifact-transfer/experiment.py begin {index} {case}'})
  measure.append({'name':f'Download {index} {arm} {case}','uses':DOWNLOAD,'timeout-minutes':4,'with':{
   'pattern':f'{"zip" if arm=="A" else "raw"}-{case}-part*','merge-multiple':True,'path':'received'}})
  measure.append({'name':f'Validate {index} {arm} {case}','run':f'python3 scripts/artifact-transfer/experiment.py end {arm}'})
measure.extend([
 {'name':'Evaluate complete trial','run':'python3 scripts/artifact-transfer/experiment.py evaluate'},
 {'name':'Retain evidence including failed trials','if':'always()','uses':UPLOAD,'with':{
  'name':'transfer-evidence','path':'evidence/\nobservations.jsonl\ndecision.json\nmanifest.json\nsample-start.json',
  'retention-days':7,'if-no-files-found':'error'}}])
workflow={'name':'benchmark-runpod-gpu','on':{'workflow_dispatch':{}},'permissions':{'contents':'read','actions':'read'},
 'concurrency':{'group':'cpu-only-raw-artifact-transfer','cancel-in-progress':False},
 'jobs':{'prepare':{'name':'Prepare ZIP and raw transport fixtures','runs-on':'ubuntu-24.04','timeout-minutes':30,'steps':prepare},
 'measure':{'name':'Compare ZIP and raw transport on CPU','needs':'prepare','runs-on':'ubuntu-24.04','timeout-minutes':45,'steps':measure}}}
(ROOT/'.github/workflows/benchmark-runpod-gpu.yml').write_text('# Generated by scripts/artifact-transfer/generate.py. CPU only; no GPU allocation.\n'+yaml.safe_dump(workflow,sort_keys=False))
