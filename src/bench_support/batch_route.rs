pub type BoxError = Box<dyn std::error::Error + Send + Sync>;

/// Whether this build can configure the Auto lane cost model.
pub const LANE_COST_POLICY_API: bool = cfg!(tenferro_lane_cost_policy);

#[derive(Clone, Debug, Deserialize)]
pub struct PolicySpec {
    pub strategy: String,
    #[serde(rename = "override")]
    pub scope: String,
    #[serde(default)]
    pub thresholds: BTreeMap<String, usize>,
}

/// One batched-route case, as generated by
/// `scripts/generate_session_matrix_cases.py`.
#[derive(Clone, Debug, Deserialize)]
pub struct CaseSpec {
    pub id: String,
    pub workload: String,
    pub operation: String,
    pub dtype: String,
    pub batch: usize,
    pub m: usize,
    pub n: usize,
    pub k: usize,
    pub subscripts: Option<String>,
    pub layout: String,
    pub output: String,
    pub policy: PolicySpec,
    #[serde(default)]
    pub pair: Option<String>,
    #[serde(default)]
    pub requires: Vec<String>,
    pub route: serde_json::Value,
}

impl CaseSpec {
    pub fn is_into(&self) -> bool {
        self.output == "into"
    }
}

/// Read every one-operation case from the instance file.
pub fn load_cases(path: &str) -> Result<Vec<CaseSpec>, BoxError> {
    let values: Vec<serde_json::Value> = serde_json::from_str(&std::fs::read_to_string(path)?)?;
    values
        .into_iter()
        .filter(|v| {
            matches!(
                v["workload"].as_str(),
                Some("batched_dot" | "batched_einsum" | "hadamard" | "chain3")
            )
        })
        .map(|v| Ok(serde_json::from_value(v)?))
        .collect()
}

/// Where a case's batch policy applies.
#[derive(Clone, Copy, Debug)]
pub enum PolicyScope {
    /// No override: the backend's default policy.
    Default,
    /// `CpuBackend::with_batch_policy`.
    Backend(CpuBatchPolicy),
    /// `tenferro_cpu::with_batch_policy` around the operations.
    Scoped(CpuBatchPolicy),
}

impl PolicyScope {
    pub fn label(&self) -> String {
        match self {
            Self::Default => "backend-default".into(),
            Self::Backend(p) => format!("backend:{p:?}"),
            Self::Scoped(p) => format!("scoped:{p:?}"),
        }
    }
}

/// Build the requested policy, or explain why this revision cannot express it.
pub fn build_policy(spec: &PolicySpec) -> Result<PolicyScope, String> {
    let strategy = match spec.strategy.as_str() {
        "auto" => CpuBatchStrategy::Auto,
        "sequential" => CpuBatchStrategy::Sequential,
        "outer_parallel" => CpuBatchStrategy::OuterParallel,
        "provider_items" => CpuBatchStrategy::ProviderItems,
        "whole_batch_vendor" => CpuBatchStrategy::WholeBatchVendor,
        other => return Err(format!("unknown batch strategy {other}")),
    };
    let mut thresholds = CpuBatchThresholds::default();
    for (knob, &value) in &spec.thresholds {
        thresholds = match knob.as_str() {
            "outer_min_items" => thresholds.with_outer_min_items(value),
            "outer_min_items_per_lane" => thresholds.with_outer_min_items_per_lane(value),
            "vendor_batch_max_item_dim" => thresholds.with_vendor_batch_max_item_dim(value),
            "lane_min_work_ns" => lane_min_work_ns(thresholds, value)?,
            other => return Err(format!("unknown threshold {other}")),
        };
    }
    let policy = CpuBatchPolicy::new(strategy).with_thresholds(thresholds);
    match spec.scope.as_str() {
        "none" => Ok(PolicyScope::Default),
        "backend" => Ok(PolicyScope::Backend(policy)),
        "scoped" => Ok(PolicyScope::Scoped(policy)),
        other => Err(format!("unknown policy scope {other}")),
    }
}

#[cfg(tenferro_lane_cost_policy)]
fn lane_min_work_ns(t: CpuBatchThresholds, value: usize) -> Result<CpuBatchThresholds, String> {
    Ok(t.with_lane_min_work_ns(value))
}

#[cfg(not(tenferro_lane_cost_policy))]
fn lane_min_work_ns(_: CpuBatchThresholds, _: usize) -> Result<CpuBatchThresholds, String> {
    Err(
        "the Auto lane cost model is not configurable at this tenferro-rs revision \
         (CpuBatchThresholds has no lane_min_work_ns; the cost model is hard-coded)"
            .into(),
    )
}

/// Construct the faer backend a case runs on, with its backend-default policy.
pub fn backend_for(
    threads: usize,
    scope: PolicyScope,
    bundle: Option<tenferro_cpu::CpuProviderBundle>,
) -> Result<CpuBackend, BoxError> {
    let mut backend = CpuBackend::with_threads_and_kind(threads, CpuBackendKind::Faer)?;
    if let Some(bundle) = bundle {
        backend = backend.with_provider_bundle(bundle)?;
    }
    if let PolicyScope::Backend(policy) = scope {
        backend = backend.with_batch_policy(policy);
    }
    Ok(backend)
}

/// Run `f` under the case's scoped policy, if any, on an entered session.
pub fn in_policy_scope<R>(
    session: &mut dyn BackendSession,
    scope: PolicyScope,
    f: impl FnOnce(&mut dyn BackendSession) -> R,
) -> Result<R, BoxError> {
    match scope {
        PolicyScope::Scoped(policy) => Ok(with_batch_policy(session, policy, f)?),
        _ => Ok(f(session)),
    }
}

/// An operation failure, split so a typed `Unsupported` stays visible as
/// unsupported instead of becoming a numerical or harness failure.
#[derive(Debug)]
pub enum OpError {
    Unsupported(String),
    Failed(String),
}

impl std::fmt::Display for OpError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Unsupported(m) => write!(f, "unsupported: {m}"),
            Self::Failed(m) => write!(f, "failed: {m}"),
        }
    }
}

fn tensor_error(e: tenferro_tensor::Error) -> OpError {
    if e.kind() == ErrorKind::Unsupported {
        OpError::Unsupported(e.to_string())
    } else {
        OpError::Failed(e.to_string())
    }
}

fn einsum_error(e: tenferro_einsum::Error) -> OpError {
    if e.kind() == ErrorKind::Unsupported {
        OpError::Unsupported(e.to_string())
    } else {
        OpError::Failed(e.to_string())
    }
}

/// Logical element value of operand `which` at a flat logical index; distinct
/// per item so a lane that writes the wrong batch slice is caught.
fn value(which: usize, index: usize) -> (f64, f64) {
    let re = ((index * (3 + which) + 7 * which) % 11) as f64 * 0.125 - 0.5;
    let im = ((index * (5 + which) + which) % 7) as f64 * 0.0625 - 0.1875;
    (re, im)
}

/// Storage for one operand plus the strides/offset that view it.
struct Operand {
    storage: Tensor,
    shape: Vec<usize>,
    strides: Vec<isize>,
    /// Owned tensors are passed with `TensorRead::from_tensor`.
    owned: bool,
}

fn col_major_strides(shape: &[usize]) -> Vec<isize> {
    let mut strides = Vec::with_capacity(shape.len());
    let mut s = 1isize;
    for &d in shape {
        strides.push(s);
        s *= d as isize;
    }
    strides
}

fn build_operand(
    which: usize,
    shape: &[usize],
    layout: &str,
    dtype: &str,
) -> Result<Operand, BoxError> {
    let strides: Vec<isize> = match (layout, shape.len()) {
        ("direct", _) => col_major_strides(shape),
        // Padded batch stride: each item stays a col-major matrix.
        ("strided", 3) => vec![1, shape[0] as isize, (shape[0] * shape[1] + 3) as isize],
        // Batch-innermost: neither matrix axis is unit-stride.
        ("canonical", 3) => vec![shape[2] as isize, (shape[2] * shape[0]) as isize, 1],
        _ => return Err(format!("unsupported layout {layout} for rank {}", shape.len()).into()),
    };
    let len = shape
        .iter()
        .zip(&strides)
        .map(|(&d, &s)| (d - 1) * s as usize)
        .sum::<usize>()
        + 1;
    let total: usize = shape.iter().product();
    let mut positions = vec![0usize; total];
    for (flat, slot) in positions.iter_mut().enumerate() {
        let mut rem = flat;
        let mut pos = 0usize;
        for (&d, &s) in shape.iter().zip(&strides) {
            pos += (rem % d) * s as usize;
            rem /= d;
        }
        *slot = pos;
    }
    let storage = match dtype {
        "f64" => {
            let mut data = vec![f64::NAN; len];
            for (flat, &pos) in positions.iter().enumerate() {
                data[pos] = value(which, flat).0;
            }
            Tensor::from_vec_col_major(vec![len], data)?
        }
        "c64" => {
            let mut data = vec![Complex64::new(f64::NAN, f64::NAN); len];
            for (flat, &pos) in positions.iter().enumerate() {
                let (re, im) = value(which, flat);
                data[pos] = Complex64::new(re, im);
            }
            Tensor::from_vec_col_major(vec![len], data)?
        }
        other => return Err(format!("unsupported dtype {other}").into()),
    };
    let owned = layout == "direct";
    let storage = if owned {
        // Owned operands carry their logical shape directly.
        match dtype {
            "f64" => {
                Tensor::from_vec_col_major(shape.to_vec(), storage.as_slice::<f64>()?.to_vec())?
            }
            _ => Tensor::from_vec_col_major(
                shape.to_vec(),
                storage.as_slice::<Complex64>()?.to_vec(),
            )?,
        }
    } else {
        storage
    };
    Ok(Operand {
        storage,
        shape: shape.to_vec(),
        strides,
        owned,
    })
}

impl Operand {
    fn read(&self) -> Result<TensorRead<'_>, BoxError> {
        if self.owned {
            return Ok(TensorRead::from_tensor(&self.storage));
        }
        let view = match self.storage.dtype() {
            tenferro_tensor::DType::F64 => TensorView::F64(TypedTensorView::from_slice(
                self.shape.clone(),
                self.strides.clone(),
                0,
                self.storage.as_slice::<f64>()?,
            )?),
            _ => TensorView::C64(TypedTensorView::from_slice(
                self.shape.clone(),
                self.strides.clone(),
                0,
                self.storage.as_slice::<Complex64>()?,
            )?),
        };
        Ok(TensorRead::from_view(view))
    }
}

/// Prepared inputs, reference output and output shape for one case. All of it
/// is built before any session is entered.
pub struct Fixture {
    operands: Vec<Operand>,
    pub out_shape: Vec<usize>,
    reference: Vec<Complex64>,
    dtype: String,
    config: DotGeneralConfig,
}

fn logical(which: usize, flat: usize, complex: bool) -> Complex64 {
    let (re, im) = value(which, flat);
    Complex64::new(re, if complex { im } else { 0.0 })
}

impl Fixture {
    pub fn new(spec: &CaseSpec) -> Result<Self, BoxError> {
        let complex = spec.dtype == "c64";
        let (m, n, k, b) = (spec.m, spec.n, spec.k, spec.batch);
        let empty = DotGeneralConfig {
            lhs_contracting_dims: [].as_slice().into(),
            rhs_contracting_dims: [].as_slice().into(),
            lhs_batch_dims: [].as_slice().into(),
            rhs_batch_dims: [].as_slice().into(),
        };
        match spec.workload.as_str() {
            "batched_dot" | "batched_einsum" => {
                let lhs = build_operand(0, &[m, k, b], &spec.layout, &spec.dtype)?;
                let rhs = build_operand(1, &[k, n, b], &spec.layout, &spec.dtype)?;
                let mut reference = vec![Complex64::new(0.0, 0.0); m * n * b];
                for bb in 0..b {
                    for j in 0..n {
                        for i in 0..m {
                            let mut acc = Complex64::new(0.0, 0.0);
                            for p in 0..k {
                                acc += logical(0, i + m * (p + k * bb), complex)
                                    * logical(1, p + k * (j + n * bb), complex);
                            }
                            reference[i + m * (j + n * bb)] = acc;
                        }
                    }
                }
                Ok(Self {
                    operands: vec![lhs, rhs],
                    out_shape: vec![m, n, b],
                    reference,
                    dtype: spec.dtype.clone(),
                    config: DotGeneralConfig {
                        lhs_contracting_dims: [1].as_slice().into(),
                        rhs_contracting_dims: [0].as_slice().into(),
                        lhs_batch_dims: [2].as_slice().into(),
                        rhs_batch_dims: [2].as_slice().into(),
                    },
                })
            }
            "hadamard" => {
                let lhs = build_operand(0, &[m, n], "direct", &spec.dtype)?;
                let rhs = build_operand(1, &[m, n], "direct", &spec.dtype)?;
                let reference = (0..m * n)
                    .map(|i| logical(0, i, complex) * logical(1, i, complex))
                    .collect();
                Ok(Self {
                    operands: vec![lhs, rhs],
                    out_shape: vec![m, n],
                    reference,
                    dtype: spec.dtype.clone(),
                    config: DotGeneralConfig {
                        lhs_batch_dims: [0, 1].as_slice().into(),
                        rhs_batch_dims: [0, 1].as_slice().into(),
                        ..empty
                    },
                })
            }
            "chain3" => {
                let ops = (0..3)
                    .map(|w| build_operand(w, &[m, m], "direct", &spec.dtype))
                    .collect::<Result<Vec<_>, _>>()?;
                let mat = |w: usize| -> Vec<Complex64> {
                    (0..m * m).map(|i| logical(w, i, complex)).collect()
                };
                let mul = |a: &[Complex64], b: &[Complex64]| -> Vec<Complex64> {
                    let mut c = vec![Complex64::new(0.0, 0.0); m * m];
                    for j in 0..m {
                        for p in 0..m {
                            for i in 0..m {
                                c[i + m * j] += a[i + m * p] * b[p + m * j];
                            }
                        }
                    }
                    c
                };
                let reference = mul(&mul(&mat(0), &mat(1)), &mat(2));
                Ok(Self {
                    operands: ops,
                    out_shape: vec![m, m],
                    reference,
                    dtype: spec.dtype.clone(),
                    config: empty,
                })
            }
            other => Err(format!("unknown workload {other}").into()),
        }
    }

    /// Prepared read handles; built once, cloned (metadata only) per call.
    pub fn reads(&self) -> Result<Vec<TensorRead<'_>>, BoxError> {
        self.operands.iter().map(Operand::read).collect()
    }

    /// Owned operand handles for the owned-tensor einsum spellings; built once
    /// outside timing.
    pub fn owned(&self) -> Vec<&Tensor> {
        self.operands.iter().map(|o| &o.storage).collect()
    }

    /// A zero-initialized caller-owned destination for `_into` routes.
    pub fn destination(&self) -> Result<Tensor, BoxError> {
        let len = self.out_shape.iter().product();
        Ok(match self.dtype.as_str() {
            "f64" => Tensor::from_vec_col_major(self.out_shape.clone(), vec![0.0_f64; len])?,
            _ => Tensor::from_vec_col_major(
                self.out_shape.clone(),
                vec![Complex64::new(0.0, 0.0); len],
            )?,
        })
    }

    /// Output bytes, for bounding retained outputs.
    pub fn output_bytes(&self) -> usize {
        let elem = if self.dtype == "f64" { 8 } else { 16 };
        self.out_shape.iter().product::<usize>() * elem
    }

    /// Maximum absolute error against the independent reference.
    pub fn check(&self, output: &Tensor) -> Result<f64, BoxError> {
        if output.shape() != self.out_shape.as_slice() {
            return Err(format!(
                "output shape {:?} != expected {:?}",
                output.shape(),
                self.out_shape
            )
            .into());
        }
        let actual: Vec<Complex64> = match self.dtype.as_str() {
            "f64" => output
                .as_slice::<f64>()?
                .iter()
                .map(|&x| Complex64::new(x, 0.0))
                .collect(),
            _ => output.as_slice::<Complex64>()?.to_vec(),
        };
        let mut worst = 0.0_f64;
        for (i, (a, e)) in actual.iter().zip(&self.reference).enumerate() {
            let err = (a - e).norm();
            if !err.is_finite() || err > 1e-12 * (1.0 + e.norm()) * 16.0 {
                return Err(format!("output {i}: {a} != expected {e}").into());
            }
            worst = worst.max(err);
        }
        Ok(worst)
    }
}

/// Execute one allocating call of the case's public route.
pub fn run_alloc(
    session: &mut dyn BackendSession,
    spec: &CaseSpec,
    fixture: &Fixture,
    reads: &[TensorRead<'_>],
    owned: &[&Tensor],
) -> Result<Tensor, OpError> {
    match spec.operation.as_str() {
        "dot_general_read" => session
            .dot_general_read(reads[0].clone(), reads[1].clone(), &fixture.config)
            .map_err(tensor_error),
        "einsum" => {
            let subscripts = spec.subscripts.as_deref().unwrap_or_default();
            if spec.layout == "direct" {
                owned.einsum(subscripts, session).map_err(einsum_error)
            } else {
                reads.einsum_read(subscripts, session).map_err(einsum_error)
            }
        }
        other => Err(OpError::Failed(format!(
            "{other} is not an allocating route"
        ))),
    }
}

/// Execute one `_into` call of the case's public route into `out`.
pub fn run_into(
    session: &mut dyn BackendSession,
    spec: &CaseSpec,
    fixture: &Fixture,
    reads: &[TensorRead<'_>],
    owned: &[&Tensor],
    out: &mut Tensor,
) -> Result<(), OpError> {
    match spec.operation.as_str() {
        "dot_general_read_into" => session
            .dot_general_read_into(
                reads[0].clone(),
                reads[1].clone(),
                &fixture.config,
                TensorWrite::from_tensor(out),
            )
            .map_err(tensor_error),
        "einsum_into" => {
            let subscripts = spec.subscripts.as_deref().unwrap_or_default();
            if spec.layout == "direct" {
                owned
                    .einsum_into(subscripts, session, TensorWrite::from_tensor(out))
                    .map_err(einsum_error)
            } else {
                reads
                    .einsum_read_into(subscripts, session, TensorWrite::from_tensor(out))
                    .map_err(einsum_error)
            }
        }
        other => Err(OpError::Failed(format!("{other} is not an _into route"))),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn spec(workload: &str, layout: &str, dtype: &str) -> CaseSpec {
        serde_json::from_value(serde_json::json!({
            "id": "t", "workload": workload, "operation": "dot_general_read", "dtype": dtype,
            "batch": 3, "m": 2, "n": 3, "k": 4, "subscripts": null, "layout": layout,
            "output": "alloc", "route": {},
            "policy": {"strategy": "auto", "override": "none", "thresholds": {}},
        }))
        .unwrap()
    }

    #[test]
    fn layouts_share_logical_values_and_the_check_rejects_wrong_output() {
        for layout in ["direct", "strided", "canonical"] {
            let fixture = Fixture::new(&spec("batched_dot", layout, "f64")).unwrap();
            let reads = fixture.reads().unwrap();
            assert_eq!(reads[0].shape(), &[2, 4, 3]);
            let zero = fixture.destination().unwrap();
            assert!(
                fixture.check(&zero).is_err(),
                "{layout}: zeros must not pass"
            );
        }
    }

    #[test]
    fn unknown_or_unavailable_policies_are_explicit() {
        let mut policy = PolicySpec {
            strategy: "auto".into(),
            scope: "backend".into(),
            thresholds: BTreeMap::from([("lane_min_work_ns".to_string(), 0)]),
        };
        assert_eq!(build_policy(&policy).is_ok(), LANE_COST_POLICY_API);
        policy.thresholds.clear();
        policy.strategy = "bogus".into();
        assert!(build_policy(&policy).is_err());
    }
}
